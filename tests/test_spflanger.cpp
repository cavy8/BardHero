static void RunTests() {
    // 1) Cross-validation against the independent Python reference,
    //    processed in ragged chunks to prove chunk-size independence
    //    (the device callback slices arbitrarily).
    {
        SpFlanger fl;
        fl.Configure(TestParams());
        fl.SetActive(true);
        constexpr std::uint32_t kN = 8192;
        std::vector<float> buf(kN * 2);
        for (std::uint64_t n = 0; n < kN; ++n)
            TestInput(n, buf[n * 2], buf[n * 2 + 1]);
        const std::uint32_t chunks[] = { 480, 37, 1024, 1, 503, 6147 };
        std::uint32_t at = 0, ci = 0;
        while (at < kN) {
            const std::uint32_t want =
                std::min(chunks[ci++ % 6], kN - at);
            fl.Process(buf.data() + at * 2, want);
            at += want;
        }
        double worst = 0.0;
        for (int k = 0; k < 128; ++k) {
            const std::uint32_t f = 64 * k + 63;
            worst = std::max(worst,
                             std::abs(buf[f * 2] - kRefL[k]));
            worst = std::max(worst,
                             std::abs(buf[f * 2 + 1] - kRefR[k]));
        }
        // float32 state vs the float64 reference through a 0.55 feedback
        // loop: observed ~1e-6; 5e-4 still fails on any structural error.
        CHECK(worst < 5e-4);
    }

    // 2) Inactive filter is a bit-exact no-op - it must never touch the
    //    buffer at all.
    {
        SpFlanger fl;
        fl.Configure(TestParams());
        std::vector<float> buf(2048 * 2), ref(2048 * 2);
        for (std::uint64_t n = 0; n < 2048; ++n)
            TestInput(n, buf[n * 2], buf[n * 2 + 1]);
        ref = buf;
        fl.Process(buf.data(), 2048);
        CHECK(std::memcmp(buf.data(), ref.data(),
                          buf.size() * sizeof(float)) == 0);
    }

    // 3) Disengage settles back to the bit-exact no-op within the ramp,
    //    ready for a clean re-engage.
    {
        SpFlanger fl;
        fl.Configure(TestParams());
        fl.SetActive(true);
        std::vector<float> buf(4096 * 2);
        for (std::uint64_t n = 0; n < 4096; ++n)
            TestInput(n, buf[n * 2], buf[n * 2 + 1]);
        fl.Process(buf.data(), 4096);
        fl.SetActive(false);
        fl.Process(buf.data(), 4096);  // ramp is 480 samples; plenty
        CHECK(fl.Idle());
        std::vector<float> ref(1024 * 2);
        for (std::uint64_t n = 0; n < 1024; ++n)
            TestInput(n, ref[n * 2], ref[n * 2 + 1]);
        auto probe = ref;
        fl.Process(probe.data(), 1024);
        CHECK(std::memcmp(probe.data(), ref.data(),
                          ref.size() * sizeof(float)) == 0);
    }

    // 4) Stability guard: an absurd feedback request is clamped and five
    //    seconds of full-scale input stays bounded (comb peak with the
    //    clamped 0.74 loop tops out well under 4x).
    {
        SpFlangerParams p = TestParams();
        p.feedback        = 0.99f;  // Configure must clamp this
        p.wet             = 1.0f;
        SpFlanger fl;
        fl.Configure(p);
        fl.SetActive(true);
        std::vector<float> buf(4800 * 2);
        float              peak = 0.0f;
        for (int block = 0; block < 50; ++block) {
            for (std::uint64_t n = 0; n < 4800; ++n) {
                const std::uint64_t g = block * 4800 + n;
                // harsh broadband: full-scale square-ish drive
                const float v = ((g / 40) % 2) ? 1.0f : -1.0f;
                buf[n * 2] = buf[n * 2 + 1] = v;
            }
            fl.Process(buf.data(), 4800);
            for (float s : buf) peak = std::max(peak, std::abs(s));
        }
        CHECK(peak < 4.0f);
        CHECK(std::isfinite(peak));
    }

    // 5) The engage ramp actually ramps: early output is nearly dry,
    //    and by the end of the ramp the wet path is audibly present.
    {
        SpFlanger fl;
        SpFlangerParams p = TestParams();
        fl.Configure(p);
        fl.SetActive(true);
        constexpr std::uint32_t kN = 2048;  // ramp = 480 samples
        std::vector<float> buf(kN * 2), dry(kN * 2);
        for (std::uint64_t n = 0; n < kN; ++n) {
            TestInput(n, buf[n * 2], buf[n * 2 + 1]);
            dry[n * 2]     = buf[n * 2];
            dry[n * 2 + 1] = buf[n * 2 + 1];
        }
        fl.Process(buf.data(), kN);
        double early = 0.0, late = 0.0;
        for (std::uint32_t f = 0; f < 48; ++f)
            early = std::max(early,
                             static_cast<double>(std::abs(
                                 buf[f * 2] - dry[f * 2])));
        for (std::uint32_t f = 1024; f < kN; ++f)
            late = std::max(late, static_cast<double>(std::abs(
                                      buf[f * 2] - dry[f * 2])));
        CHECK(early < 0.15);   // first ms: wet is barely open
        CHECK(late > 0.05);    // settled: the effect is unmistakably there
        CHECK(late > early);
    }
}


// The deterministic test signal, identical (in double) to the generator in
// the sound session's reference script. Any change here must be mirrored
// there and the checkpoints regenerated.
static void TestInput(std::uint64_t n, float& l, float& r) {
    const double t = static_cast<double>(n) / 48000.0;
    constexpr double kTau = 6.28318530717958647692;
    l = static_cast<float>(0.4 * std::sin(kTau * 220.0 * t) +
                           0.2 * std::sin(kTau * 917.0 * t + 0.5));
    r = static_cast<float>(0.4 * std::sin(kTau * 220.0 * t + 0.3) +
                           0.2 * std::sin(kTau * 1333.0 * t));
}

// Fast test parameters: a full LFO cycle plus the whole engage ramp fit
// inside 8192 frames. The audible "classic" defaults share every code
// path; only the numbers differ.
static SpFlangerParams TestParams() {
    SpFlangerParams p;
    p.rateHz      = 8.0f;
    p.baseMs      = 0.4f;
    p.depthMs     = 3.6f;
    p.feedback    = 0.55f;
    p.wet         = 0.8f;
    p.stereoPhase = 0.25f;
    p.trimDb      = -2.5f;
    p.rampSec     = 0.010f;
    return p;
}

